import { catalog, createItem, getSpend } from "./model.js";
import { HOUSE_UNITS, normalizeHouse, toSceneObject } from "./house-model.js";

function catalogProduct(id) {
  const found = catalog.find((product) => product.id === id);
  if (!found) throw new Error(`Missing catalog product: ${id}`);
  return found;
}

function fixedFixture({
  id,
  kind,
  name,
  roomId,
  color,
  x,
  z,
  elevation = 0,
  rotation = 0,
  width,
  depth,
  height,
}) {
  const yawRad = (rotation * Math.PI) / 180;
  return {
    id,
    type: "fixed",
    kind,
    name,
    roomId,
    color,
    position: [x, elevation, z],
    rotation: [0, yawRad, 0],
    dimensions: { width, height, depth },
    locked: true,
  };
}

function movablePiece(
  productId,
  { id, roomId, x, z, rotation = 0, owned = false, name },
) {
  const product = catalogProduct(productId);
  const base = createItem(name ? { ...product, name } : product, {
    id,
    x,
    z,
    rotation,
    owned,
  });
  return toSceneObject({
    ...base,
    roomId,
    type: owned ? "existing" : "shopify",
    locked: false,
  });
}

