import { catalog, createItem, getSpend } from "./model.js";
import { normalizeHouse, toSceneObject } from "./house-model.js";

function catalogProduct(id) {
  const found = catalog.find((product) => product.id === id);
  if (!found) throw new Error(`Missing catalog product: ${id}`);
  return found;
}

function fixedFixture({
  id,
  kind,
  name,
  roomId,
  color,
  x,
  z,
  elevation = 0,
  rotation = 0,
  width,
  depth,
  height,
}) {
  return toSceneObject({
    id,
    productId: null,
    type: "fixed",
    kind,
    name,
    roomId,
    color,
    x,
    y: elevation,
    elevation,
    z,
    rotation,
    width,
    depth,
    height,
    owned: true,
    locked: true,
    price: 0,
  });
}

function movablePiece(productId, { id, roomId, x, z, rotation = 0, owned = false, name }) {
  const product = catalogProduct(productId);
  const base = createItem(
    name ? { ...product, name } : product,
    { id, x, z, rotation, owned },
  );
  return toSceneObject({
    ...base,
    roomId,
    type: owned ? "existing" : "shopify",
    locked: false,
  });
}

